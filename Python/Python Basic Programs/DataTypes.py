# 1. str

a = "Hello World"
print("Type of a:",type(a))
print()

# 2. int

a = 20
print("Type of a:",type(a))
print()

# 3. float

a = 20.5
print("Type of a:",type(a))
print()

# 4. complex

a = 1j
print("Type of a:",type(a))
print()

# 5. list

a = ["apple", "banana", "cherry"]
print("Type of a:",type(a))
print()

# 6. tuple

a = ("apple", "banana", "cherry")
print("Type of a:",type(a))
print()

# 7. range

a = range(6)
print("Type of a:",type(a))
print()

# 8. dict

a = {"name" : "John", "age" : 36}
print("Type of a:",type(a))
print()

# 9. set

a = {"apple", "banana", "cherry"}
print("Type of a:",type(a))
print()

# 10. frozenset

a = frozenset({"apple", "banana", "cherry"})
print("Type of a:",type(a))
print()

# 11. bool

a = True
print("Type of a:",type(a))
print()

# 12. bytes

a = b"Hello"
print("Type of a:",type(a))
print()

# 13. bytearray

a = bytearray(5)
print("Type of a:",type(a))
print()

# 14. memoryview

a = memoryview(bytes(5))
print("Type of a:",type(a))
print()

# 15. NoneType

a = None
print("Type of a:",type(a))
print()
