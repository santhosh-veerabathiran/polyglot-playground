# 1. count(value)

tup1 = ("apple", "cherry", "banana", "cherry")
print("Tuple:", tup1)
print("Count (cherry):", tup1.count("cherry"))
print()

# 2. index(object[,start[,end]])

tup2 = ("apple", "banana", "cherry")
print("Tuple:", tup2)
print("Index (banana):", tup2.index("banana"))
print()

# 3. len(object)

tup3 = (5, 10, 15, 20, 25, 30)
print("Tuple:", tup3)
print("Length:", len(tup3))
print()

# 4. min(object)

tup4 = (10, 15, 5, 20, 30, 25)
print("Tuple:", tup4)
print("Minimum:", min(tup4))
print()

# 5. max(object)

tup5 = (10, 15, 5, 20, 30, 25)
print("Tuple:", tup5)
print("Maximum:", max(tup5))
print()
